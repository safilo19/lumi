// Regenerates public/sw.js with a fresh BUILD_ID on every build/dev start so
// browsers detect a byte-different service worker and surface the in-app
// "update available" prompt. Runs via the predev/prebuild npm hooks.
import { writeFile, readFile } from "node:fs/promises";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));

let rev = String(Date.now());
try {
  rev =
    execSync("git rev-parse --short HEAD", {
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim() || rev;
} catch {}
const BUILD_ID = `${pkg.version}+${rev}`;

const offlineHtml =
  '<!doctype html><html lang="en"><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width,initial-scale=1">' +
  "<title>Offline — Lumi</title><style>body{margin:0;min-height:100vh;" +
  "display:flex;align-items:center;justify-content:center;background:#5b4df6;" +
  "color:#fffdf8;font-family:system-ui,sans-serif;text-align:center;padding:24px}" +
  "h1{font-size:1.5rem;margin:0 0 .5rem}p{opacity:.85;margin:0}</style></head>" +
  "<body><div><h1>You're offline</h1><p>Lumi needs a connection to load " +
  "this page. Reconnect and try again.</p></div></body></html>";

// __APPEND_SW__
const sw = `/* Lumi service worker — generated by scripts/gen-sw.mjs. Do not edit. */
const BUILD_ID = ${JSON.stringify(BUILD_ID)};
const CACHE = "lumi-" + BUILD_ID;
const ASSETS = ["/icon.svg", "/icon-192.png", "/icon-512.png", "/apple-icon.png", "/manifest.webmanifest"];
const OFFLINE_HTML = ${JSON.stringify(offlineHtml)};

self.addEventListener("install", (event) => {
  // No skipWaiting: staying "waiting" is what lets the app show the update
  // prompt. The page posts SKIP_WAITING when the user accepts the update.
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).catch(() => {}));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/")) return; // never cache API / auth

  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req).catch(() =>
        new Response(OFFLINE_HTML, { headers: { "Content-Type": "text/html; charset=utf-8" } })
      )
    );
    return;
  }

  if (url.pathname.startsWith("/_next/static/") || ASSETS.includes(url.pathname)) {
    event.respondWith(
      caches.match(req).then((hit) =>
        hit ||
        fetch(req).then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        })
      )
    );
  }
});
`;

await writeFile(path.join(root, "public", "sw.js"), sw);
console.log("wrote public/sw.js (BUILD_ID " + BUILD_ID + ")");

